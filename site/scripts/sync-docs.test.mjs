test("the title is the first H1 after HTML comments", () => {
  const { title, body } = splitTitle("<!-- Generated by make docs.\n Do not edit. -->\n\n# sonde `check`\n\nCheck files.\n");
  assert.equal(title, "sonde check");
  assert.equal(body, "Check files.\n");
  assert.throws(() => splitTitle("Intro\n\n# Late title"), /first line/);
});

test("YAML-hostile titles and descriptions round-trip", () => {
  const data = { title: 'Streaming: SSE "and" WebSocket', description: "a: b # c — `x` 'y' {z} [w] *v &u !t |s >r", source: "docs/x.md" };
  const text = frontmatter(data);
  assert.deepEqual(parse(text.replace(/^---\n|---\n\n$/g, "")), data);
});

test("first paragraph is the fallback description", () => {
  assert.equal(firstParagraph("\n```sh\nx\n```\n\nSee [the guide](g.md) for `--jobs`.\nMore.\n\nNext."), "See the guide for --jobs. More.");
});

