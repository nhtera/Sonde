/** A minimal repository with the docs layout the nav expects. */
function fixtureRepo({ shallow = false } = {}) {
  const repo = mkdtempSync(join(tmpdir(), "sonde-sync-"));
  const w = (rel, text) => {
    mkdirSync(join(repo, rel, ".."), { recursive: true });
    writeFileSync(join(repo, rel), text);
  };
  const docs = ["getting-started", "desktop", "file-format", "sonde-yaml", "report-json", "compat", "stability", "security", "benchmarks"];
  w("docs/README.md", `# Docs\n\n| Document | Contents |\n|---|---|\n${docs.map((d) => `| [${d}.md](${d}.md) | About ${d} |`).join("\n")}\n| [cli/README.md](cli/README.md) | Every command (generated, \`make docs\`) |\n| [guides/a.md](guides/a.md) | Guide A |\n| [architecture.md](architecture.md) | Internals |\n`);
  w("docs/cli/README.md", "<!-- Generated -->\n\n# CLI reference\n\n- [sonde](sonde.md) — Run requests\n");
  w("docs/cli/sonde.md", "<!-- Generated -->\n\n# sonde\n\nRun.\n");
  w("docs/guides/a.md", "# Guide: A\n\nText.\n");
  w("docs/architecture.md", "# Internals\n");
  for (const d of docs) w(`docs/${d}.md`, `# ${d}\n\nBody of ${d}.\n`);
  w("README.md", "# Sonde\n\n## Install\n\n**Go:**\n\n```sh\ngo install x@latest\n```\n\n## Next\n");
  const git = (...args) => execFileSync("git", args, { cwd: repo, env: { ...process.env, GIT_CONFIG_GLOBAL: "/dev/null", GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@t", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@t" } });
  git("init", "-q", "-b", "main");
  git("add", "-A");
  git("commit", "-qm", "init");
  if (!shallow) return repo;
  const clone = mkdtempSync(join(tmpdir(), "sonde-sync-shallow-"));
  execFileSync("git", ["clone", "-q", "--depth", "1", `file://${repo}`, clone]);
  rmSync(repo, { recursive: true, force: true });
  return clone;
}

test("sync writes docs with frontmatter, meta.json and generated data", () => {
  const repo = fixtureRepo();
  const out = join(repo, "out");
  const logs = [];
  const { unpublished } = sync({ repo, out, log: (m) => logs.push(m) });
  const page = readFileSync(join(out, "docs/guides/a.md"), "utf8");
  assert.match(page, /^---\ntitle: "Guide: A"\ndescription: Guide A\nsource: docs\/guides\/a\.md\nlastUpdated: \d{4}-\d{2}-\d{2}\n---\n\nText\.\n$/);
  const cliIndex = readFileSync(join(out, "docs/cli/index.md"), "utf8");
  assert.match(cliIndex, /title: CLI reference\ndescription: Every command\n/);
  assert.match(readFileSync(join(out, "docs/cli/sonde.md"), "utf8"), /description: Run requests/);
  assert.deepEqual(JSON.parse(readFileSync(join(out, "docs/cli/meta.json"), "utf8")).pages, ["index", "sonde"]);
  assert.deepEqual(unpublished, ["architecture.md"]);
  assert.ok(logs.some((l) => l.startsWith("unpublished docs: architecture.md")));
  assert.deepEqual(JSON.parse(readFileSync(join(out, "generated/install.json"), "utf8")), [{ id: "go", label: "Go", command: "go install x@latest" }]);
  assert.ok(JSON.parse(readFileSync(join(out, "generated/inputs.json"), "utf8")).includes("docs/guides/a.md"));
  // Idempotent: a second run gives the same files.
  sync({ repo, out, log: () => {} });
  assert.equal(readFileSync(join(out, "docs/guides/a.md"), "utf8"), page);
  rmSync(repo, { recursive: true, force: true });
});

test("sync fails on a missing doc, a bad name, a missing H1 and a shallow clone", () => {
  let repo = fixtureRepo();
  rmSync(join(repo, "docs/guides/a.md"));
  assert.throws(() => sync({ repo, out: join(repo, "out"), dates: false, log: () => {} }), /docs\/guides\/a\.md: listed in the docs nav but missing/);
  rmSync(repo, { recursive: true, force: true });

  repo = fixtureRepo();
  writeFileSync(join(repo, "docs/README.md"), readFileSync(join(repo, "docs/README.md"), "utf8").replace("guides/a.md](guides/a.md)", "guides/A b.md](guides/A b.md)"));
  assert.throws(() => sync({ repo, out: join(repo, "out"), dates: false, log: () => {} }));
  rmSync(repo, { recursive: true, force: true });

  repo = fixtureRepo();
  writeFileSync(join(repo, "docs/guides/a.md"), "No heading here.\n");
  assert.throws(() => sync({ repo, out: join(repo, "out"), dates: false, log: () => {} }), /"# Title" heading/);
  rmSync(repo, { recursive: true, force: true });

  repo = fixtureRepo({ shallow: true });
  assert.throws(() => sync({ repo, out: join(repo, "out"), log: () => {} }), /shallow clone/);
  sync({ repo, out: join(repo, "out"), dates: false, log: () => {} });
  assert.doesNotMatch(readFileSync(join(repo, "out/docs/guides/a.md"), "utf8"), /lastUpdated/);
  rmSync(repo, { recursive: true, force: true });
});
